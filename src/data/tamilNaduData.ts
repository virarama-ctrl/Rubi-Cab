/**
 * Dynamic Statewide Search Function
 * Searches across all 38 districts, cities, towns, and landmarks.
 * If user types a new address or town in Tamil Nadu, dynamically geocodes based on
 * district headquarters or closest known coordinates.
 */
export function searchTamilNaduLocations(query: string): LocationPoint[] {
  if (!query || query.trim().length === 0) {
    return STATEWIDE_TAMIL_NADU_LOCATIONS.slice(0, 10);
  }

  const cleanQuery = query.trim().toLowerCase();

  // 1. Exact or partial match on pre-indexed landmarks
  const matchedLocations = STATEWIDE_TAMIL_NADU_LOCATIONS.filter((loc) => {
    return (
      loc.name.toLowerCase().includes(cleanQuery) ||
      loc.address.toLowerCase().includes(cleanQuery) ||
      (loc.district && loc.district.toLowerCase().includes(cleanQuery)) ||
      (loc.city && loc.city.toLowerCase().includes(cleanQuery)) ||
      (loc.tamilName && loc.tamilName.includes(query))
    );
  });

  // 2. Also check if the query matches any Tamil Nadu district or its major cities
  const matchedDistricts = TAMIL_NADU_DISTRICTS.filter(
    (dist) =>
      dist.name.toLowerCase().includes(cleanQuery) ||
      dist.tamilName.includes(query) ||
      dist.majorCities.some((c) => c.toLowerCase().includes(cleanQuery))
  );

  const districtLocations: LocationPoint[] = matchedDistricts.map((dist) => {
    return {
      id: `dist_${dist.id}`,
      name: `${dist.name} City Central`,
      tamilName: `${dist.tamilName} நகர் மையம்`,
      address: `${dist.headquarters}, ${dist.name} District, Tamil Nadu`,
      lat: dist.lat,
      lng: dist.lng,
      district: dist.name,
      city: dist.headquarters,
      placeId: `dist_place_${dist.id}`,
      category: 'station',
    };
  });

  // Combine and deduplicate
  const combined = [...matchedLocations];
  for (const dl of districtLocations) {
    if (!combined.some((c) => c.id === dl.id || (c.district?.toLowerCase() === dl.district?.toLowerCase() && c.category === 'station'))) {
      combined.push(dl);
    }
  }

  // 3. Fallback: If no matches, generate a valid Tamil Nadu query location
  if (combined.length === 0 && query.trim().length >= 3) {
    // Check if query mentions any district
    const matchedDistrict = TAMIL_NADU_DISTRICTS.find(
      (d) =>
        query.toLowerCase().includes(d.name.toLowerCase()) ||
        query.toLowerCase().includes(d.headquarters.toLowerCase())
    );

    const lat = matchedDistrict ? matchedDistrict.lat : 11.1271;
    const lng = matchedDistrict ? matchedDistrict.lng : 78.6569;
    const districtName = matchedDistrict ? matchedDistrict.name : 'Tamil Nadu';

    combined.push({
      id: `dyn_${Date.now()}`,
      name: `${query.trim()} (${districtName})`,
      tamilName: `${query.trim()} (தமிழ்நாடு)`,
      address: `${query.trim()}, ${districtName}, Tamil Nadu, India`,
      lat,
      lng,
      district: districtName,
      city: matchedDistrict ? matchedDistrict.headquarters : districtName,
      category: 'custom',
    });
  }

  return combined.slice(0, 8);
}

/**
 * Find the district in Tamil Nadu that contains or is closest to a given coordinate.
 */
export function getDistrictFromCoordinates(lat: number, lng: number): TamilNaduDistrict {
  let closest = TAMIL_NADU_DISTRICTS[0];
  let minDistance = Infinity;

  for (const dist of TAMIL_NADU_DISTRICTS) {
    const dLat = dist.lat - lat;
    const dLng = dist.lng - lng;
    const distSq = dLat * dLat + dLng * dLng;
    if (distSq < minDistance) {
      minDistance = distSq;
      closest = dist;
    }
  }

  return closest;
}
